//! Lean proof-code generation.
//!
//! [`LeanCompiler`] deterministically turns a [`LeanTheorem`] plus
//! [`ProofOptions`] into a self-contained Lean source file. The generation is
//! pure and side-effect free, which makes it fully unit-testable without a Lean
//! toolchain; the job runner then executes the produced source inside a
//! sandboxed container.

use crate::config::LeanConfig;
use crate::proto::spec_to_proof::v1::LeanTheorem;
use crate::{BoxError, LeanFarmError, ProofOptions};

#[derive(Clone, Debug)]
pub struct LeanCompiler {
    config: LeanConfig,
}

impl LeanCompiler {
    pub fn new(config: &LeanConfig) -> Self {
        Self {
            config: config.clone(),
        }
    }

    /// Generate the Lean source used to attempt a proof of `theorem`.
    ///
    /// The proof tactic block is selected from `options.proof_strategy`. The
    /// output is deterministic for a given input, which is important for
    /// content-addressed artifact storage.
    pub async fn generate_proof(
        &self,
        theorem: &LeanTheorem,
        options: &ProofOptions,
    ) -> Result<String, BoxError> {
        if theorem.lean_code.trim().is_empty() {
            return Err(LeanFarmError::LeanCompilation(format!(
                "theorem {} has empty lean_code",
                theorem.id
            ))
            .into());
        }

        let tactic = Self::tactic_for_strategy(&options.proof_strategy);
        let body = if Self::has_proof_body(&theorem.lean_code) {
            theorem.lean_code.trim_end().to_string()
        } else {
            format!("{} := {tactic}", theorem.lean_code.trim_end())
        };

        // Import lines are operator-configured. The default is empty so the
        // generated proof depends only on the Lean standard library and can be
        // checked in the stock `leanprover/lean4` image fully offline. Deploy
        // with `lean.imports = ["Mathlib"]` against a Mathlib-provisioned image
        // when richer automation is required.
        let imports = if self.config.imports.is_empty() {
            String::new()
        } else {
            let lines = self
                .config
                .imports
                .iter()
                .map(|module| format!("import {module}"))
                .collect::<Vec<_>>()
                .join("\n");
            format!("{lines}\n\n")
        };

        Ok(format!(
            "-- Generated by lean-farm (toolchain {})\n\
             -- Theorem: {}\n\
             -- Strategy: {}\n\
             {}{}\n",
            self.config.lean_version, theorem.theorem_name, options.proof_strategy, imports, body
        ))
    }

    /// Map a strategy name to a Lean tactic block. Unknown strategies fall back
    /// to a robust general-purpose tactic sequence.
    fn tactic_for_strategy(strategy: &str) -> &'static str {
        match strategy {
            "simp" => "by simp_all",
            "omega" => "by omega",
            "decide" => "by decide",
            "ring" => "by ring",
            _ => "by\n  intros\n  simp_all\n  <;> first | omega | decide | rfl",
        }
    }

    /// Detect whether the supplied Lean code already contains its own proof
    /// (a `:=` assignment). If so we do not append a tactic block.
    fn has_proof_body(code: &str) -> bool {
        code.contains(":=")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::proto::spec_to_proof::v1::LeanTheorem;

    fn theorem(code: &str) -> LeanTheorem {
        LeanTheorem {
            id: "t1".to_string(),
            theorem_name: "my_theorem".to_string(),
            lean_code: code.to_string(),
            ..Default::default()
        }
    }

    #[tokio::test]
    async fn appends_tactic_when_missing() {
        let compiler = LeanCompiler::new(&LeanConfig::default());
        let opts = ProofOptions {
            proof_strategy: "omega".to_string(),
            ..Default::default()
        };
        let out = compiler
            .generate_proof(&theorem("theorem my_theorem : 1 + 1 = 2"), &opts)
            .await
            .unwrap();
        assert!(out.contains("my_theorem"));
        assert!(out.contains("Strategy: omega"));
        assert!(out.contains(":= by omega"));
    }

    #[tokio::test]
    async fn preserves_existing_proof_body() {
        let compiler = LeanCompiler::new(&LeanConfig::default());
        let out = compiler
            .generate_proof(
                &theorem("theorem my_theorem : True := trivial"),
                &ProofOptions::default(),
            )
            .await
            .unwrap();
        assert!(out.contains(":= trivial"));
        // No second assignment appended.
        assert_eq!(out.matches(":=").count(), 1);
    }

    #[tokio::test]
    async fn deterministic_output() {
        let compiler = LeanCompiler::new(&LeanConfig::default());
        let opts = ProofOptions::default();
        let t = theorem("theorem my_theorem : 2 = 2");
        let a = compiler.generate_proof(&t, &opts).await.unwrap();
        let b = compiler.generate_proof(&t, &opts).await.unwrap();
        assert_eq!(a, b);
    }

    #[tokio::test]
    async fn empty_code_is_rejected() {
        let compiler = LeanCompiler::new(&LeanConfig::default());
        let err = compiler
            .generate_proof(&theorem("   "), &ProofOptions::default())
            .await
            .unwrap_err();
        assert!(err.to_string().contains("empty lean_code"));
    }
}
